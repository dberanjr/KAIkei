import Foundation

/// Something that happened in a session besides a billed response: the moments worth marking on a timeline.
public struct SessionEvent: Identifiable, Equatable, Sendable {
    public enum Kind: Equatable, Sendable {
        /// A message the user typed. `preview` is the first ~100 characters, kept in memory only for hover text.
        case prompt(preview: String)
        /// A slash command such as `/clear` or `/model`.
        case command(name: String)
        /// A context compaction. Claude Code records how big the context was before and after.
        case compact(trigger: String, preTokens: Int?, postTokens: Int?, durationMs: Int?)
    }

    public var id: String
    public var sessionID: String
    public var timestamp: Date
    public var kind: Kind
    /// Sub-agent traffic runs in its own conversation, so it is flagged rather than mixed into the main timeline.
    public var isSidechain: Bool
}

extension TranscriptParser {
    private static let userMarker = Data(#""type":"user""#.utf8)
    private static let compactMarker = Data(#""subtype":"compact_boundary""#.utf8)
    private static let toolResultMarker = Data(#""type":"tool_result""#.utf8)

    /// Text the harness injects into user rows. None of it was typed by the person.
    private static let injectedPrefixes = [
        "<system-reminder>", "<local-command-", "<bash-", "<task-notification", "<user-prompt-submit-hook", "<command-message>",
        "<teammate", "Caveat: The messages below were generated by the user while running local commands",
    ]
    private static let previewLimit = 400

    /// Returns an event for rows the timeline cares about; nil for everything else. Like `parse(line:)` it filters on
    /// raw bytes first, because most rows in a transcript are large blobs that are not worth decoding.
    public static func parseEvent(line: Data) -> SessionEvent? {
        let isUser = line.range(of: userMarker) != nil
        let isCompact = !isUser && line.range(of: compactMarker) != nil
        guard isUser || isCompact else { return nil }
        // Tool results are the bulk of user rows and are never prompts; `"type":"tool_result"` only appears raw as structure.
        if isUser, line.range(of: toolResultMarker) != nil { return nil }
        guard let root = (try? JSONSerialization.jsonObject(with: line)) as? [String: Any],
            let sessionID = root["sessionId"] as? String
        else { return nil }
        let ts = (root["timestamp"] as? String).flatMap { isoFractional.date(from: $0) ?? isoPlain.date(from: $0) }
        guard let ts else { return nil }
        let sidechain = root["isSidechain"] as? Bool ?? false

        func event(_ kind: SessionEvent.Kind, id fallback: String) -> SessionEvent {
            SessionEvent(id: root["uuid"] as? String ?? "\(sessionID)|\(ts.timeIntervalSince1970)|\(fallback)",
                         sessionID: sessionID, timestamp: ts, kind: kind, isSidechain: sidechain)
        }

        if isCompact {
            guard root["type"] as? String == "system", root["subtype"] as? String == "compact_boundary" else { return nil }
            let meta = root["compactMetadata"] as? [String: Any] ?? [:]
            func int(_ key: String) -> Int? { (meta[key] as? NSNumber)?.intValue }
            return event(.compact(trigger: meta["trigger"] as? String ?? "unknown", preTokens: int("preTokens"),
                                  postTokens: int("postTokens"), durationMs: int("durationMs")), id: "compact")
        }

        guard root["type"] as? String == "user", root["isMeta"] as? Bool != true, root["isCompactSummary"] as? Bool != true,
            let text = userText(root["message"])
        else { return nil }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.hasPrefix("<command-name>") {
            guard let name = commandName(in: trimmed) else { return nil }
            return event(.command(name: name), id: name)
        }
        if trimmed.isEmpty || injectedPrefixes.contains(where: { trimmed.hasPrefix($0) }) { return nil }
        return event(.prompt(preview: preview(of: trimmed)), id: "prompt")
    }

    /// The typed text, from either a plain string or a list of text blocks. Nil when the row carries no text at all.
    private static func userText(_ message: Any?) -> String? {
        guard let message = message as? [String: Any] else { return nil }
        if let s = message["content"] as? String { return s }
        guard let blocks = message["content"] as? [[String: Any]] else { return nil }
        let texts = blocks.compactMap { $0["type"] as? String == "text" ? $0["text"] as? String : nil }
        return texts.isEmpty ? nil : texts.joined(separator: " ")
    }

    private static func commandName(in text: String) -> String? {
        guard let open = text.range(of: "<command-name>"), let close = text.range(of: "</command-name>", range: open.upperBound..<text.endIndex)
        else { return nil }
        let name = text[open.upperBound..<close.lowerBound].trimmingCharacters(in: .whitespaces)
        return name.isEmpty ? nil : name
    }

    private static func preview(of text: String) -> String {
        let collapsed = text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return collapsed.count > previewLimit ? String(collapsed.prefix(previewLimit)) + "…" : collapsed
    }
}
